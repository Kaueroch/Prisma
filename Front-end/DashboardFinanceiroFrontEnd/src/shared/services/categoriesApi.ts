/**
 * categoriesApi - HTTP call service for the backend (Spring Boot)
 *
 * Available endpoints:
 *   - GET    /api/v1/categoria/listar              → List all user categories
 *   - POST   /api/v1/categoria/criarCategoria       → Create a new category
 *   - PUT    /api/v1/categoria/atualizarLista?id={id} → Update name/type by cd_id
 *   - DELETE /api/v1/categoria/deletar?id={id}      → Delete a category by cd_id
 *
 * Auth: uses the Bearer JWT token stored in localStorage (key: prisma_auth_token)
 */

import { getUserIdFromToken } from '../utils/token';

const API_URL = import.meta.env.VITE_API_URL ?? 'http://localhost:8080';

/** localStorage key where the logged-in user JWT is stored */
const TOKEN_STORAGE_KEY = 'prisma_auth_token';

/** Interface for a category returned by the backend */
export interface BackendCategoria {
  id: number;           // real cd_id generated by the database
  nome: string;         // Category name (e.g. "Food")
  tipoCategoria: string;
  userId?: string | null;
}

/** Creation payload sent to the backend - fields match CategoriaDTO */
export interface CriarCategoriaPayload {
  nome: string;
  tipoCategoria: string;
  userId: string;    // Logged-in user UUID (JWT "sub" claim)
}

/** Update payload - only the editable fields + the category id (CategoriaDTO) */
export interface AtualizarCategoriaPayload {
  id: number;
  nome: string;
  tipoCategoria: string;
}

/** Read the stored JWT from localStorage for auth */
function getToken(): string | null {
  return localStorage.getItem(TOKEN_STORAGE_KEY);
}

/** Get the logged-in user ID (UUID) from the stored JWT */
export function getLoggedUserId(): string | null {
  return getUserIdFromToken(getToken());
}

/** Build the auth headers for HTTP requests */
function authHeaders(): Record<string, string> {
  const token = getToken();
  return {
    'Content-Type': 'application/json',
    ...(token ? { Authorization: `Bearer ${token}` } : {}),
  };
}

export const categoriesApi = {
  /**
   * List all categories for the logged-in user.
   * Calls: GET /api/v1/categoria/listar?userId={uuid}
   * The endpoint requires userId as a query param, so we send the UUID from the JWT.
   */
  async listar(userId?: string | null): Promise<BackendCategoria[]> {
    const query = userId ? `?userId=${encodeURIComponent(userId)}` : '';
    const response = await fetch(`${API_URL}/api/v1/categoria/listar${query}`, {
      headers: authHeaders(),
    });
    if (!response.ok) {
      const text = await response.text();
      throw new Error(text || 'Could not load categories');
    }
    const data = await response.json();
    if (!Array.isArray(data)) {
      throw new Error('Unexpected backend response while loading categories.');
    }
    return data as BackendCategoria[];
  },

  /**
   * Create a new category in the backend and return the database-generated cd_id.
   * Calls: POST /api/v1/categoria/criarCategoria
   */
  async criar(payload: CriarCategoriaPayload): Promise<number> {
    const response = await fetch(`${API_URL}/api/v1/categoria/criarCategoria`, {
      method: 'POST',
      headers: authHeaders(),
      body: JSON.stringify(payload),
    });
    if (!response.ok) {
      const text = await response.text();
      throw new Error(text || 'Could not create category');
    }
    const data = await response.json();
    return Number(data.id);
  },

  /**
   * Update an existing category by sending an object (name/type) plus the id.
   * Calls: PUT /api/v1/categoria/atualizarLista?id={categoriaId}
   *
   * The id goes in the query (same as delete) and the object with the
   * editable fields goes in the request body.
   */
  async atualizar(categoriaId: number, payload: AtualizarCategoriaPayload): Promise<void> {
    const response = await fetch(
      `${API_URL}/api/v1/categoria/atualizarLista?id=${encodeURIComponent(String(categoriaId))}`,
      {
        method: 'PUT',
        headers: authHeaders(),
        body: JSON.stringify(payload),
      },
    );
    if (!response.ok) {
      const text = await response.text();
      throw new Error(text || 'Could not update category');
    }
  },

  /**
   * Delete a category by its real cd_id and return the removed record.
   * Calls: DELETE /api/v1/categoria/deletar?id={categoriaId}
   *
   * The category owner is validated in the backend via the JWT token, so here
   * we only send the id - never the whole object or a fabricated id.
   */
  async deletar(categoriaId: number): Promise<BackendCategoria> {
    const response = await fetch(
      `${API_URL}/api/v1/categoria/deletar?id=${encodeURIComponent(String(categoriaId))}`,
      {
        method: 'DELETE',
        headers: authHeaders(),
      },
    );
    if (!response.ok) {
      const text = await response.text();
      throw new Error(text || 'Could not delete category');
    }
    return (await response.json()) as BackendCategoria;
  },
};
