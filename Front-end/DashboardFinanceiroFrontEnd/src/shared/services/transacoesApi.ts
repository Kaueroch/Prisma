import { getUserIdFromToken } from '../utils/token';
import { API_URL, authHeaders, getToken, readErrorBody } from './api';

/**
 * transacoesApi - HTTP client for the backend (Spring Boot)
 *
 * Endpoints used by the app:
 *   - GET  /api/v1/transacao/listar → List the transactions of the logged-in user
 *   - POST /api/v1/transacao/criar  → Create a new transaction (returns the cd_id)
 *
 * Auth: uses the Bearer JWT token stored in localStorage (key: prisma_auth_token).
 * The backend secures these routes (anyRequest().authenticated()), so the token
 * is mandatory — same pattern as categoriesApi.
 *
 * Backend contract (TransacaoDTO.java record):
 *   - valor:       number (BigDecimal, vl_valor, not null)
 *   - descricao:   string (ds_descricao, not null, not blank)
 *   - data:        string (dt_dataGasto, not null, format "dd/MM/yyyy")
 *   - categoria_id: number (FK categoria_id, Integer — id direto, sem objeto)
 *
 * Response contract (TransacaoResponseDTO.java record):
 *   - id:            the cd_id generated by the database
 *   - categoria_nome / categoria_tipo: from the linked category
 */

/** Payload in backend shape (matches TransacaoDTO record field names) */
export interface CriarTransacaoPayload {
  valor: number;
  descricao: string;
  /** Date in "dd/MM/yyyy" — the only format Transacao.converteStringToDate parses */
  data: string;
  categoria_id: number;
  /** Logged-in user UUID — backend confere com o dono do token, nunca confia só nele */
  user_id: string | null;
  /** Observação opcional */
  observacao?: string | null;
}

/** Friendly input from the transaction form (date comes as yyyy-MM-dd from <input type="date">) */
export interface NovaTransacaoInput {
  valor: number;
  descricao: string;
  /** Date as "yyyy-MM-dd" (HTML date input value) */
  data: string;
  categoriaId: string | number;
  /** Observação opcional */
  observacao?: string;
}

/** Transação como o back-end devolve (TransacaoResponseDTO) */
export interface BackendTransacao {
  /** cd_id gerado pelo banco */
  id: number;
  valor: number;
  descricao: string;
  /** "dd/MM/yyyy" */
  data: string;
  categoria_id: number | null;
  categoria_nome: string | null;
  /** "Despesas" ou "Receita" */
  categoria_tipo: string | null;
  observacao: string | null;
}

/** Convert "yyyy-MM-dd" → "dd/MM/yyyy" as required by Transacao.java */
export function toBackendDate(isoDate: string): string {
  const [year, month, day] = isoDate.split('-');
  if (!year || !month || !day) {
    throw new Error(`Data inválida "${isoDate}". Formato esperado: aaaa-mm-dd.`);
  }
  return `${day}/${month}/${year}`;
}

function defaultErrorForStatus(status: number, action = 'criar'): string {
  if (status === 401 || status === 403) return 'Sessão expirada. Entre novamente.';
  if (status === 404) return `Endpoint não encontrado (/api/v1/transacao/${action}).`;
  if (status >= 500) return `O backend não conseguiu ${action} a transação. Verifique os logs do backend.`;
  return `Não foi possível ${action} a transação. Confira os campos e tente de novo.`;
}

export const transacoesApi = {
  /**
   * List the transactions of the logged-in user.
   * Calls: GET /api/v1/transacao/listar
   */
  async listar(): Promise<BackendTransacao[]> {
    const response = await fetch(`${API_URL}/api/v1/transacao/listar`, {
      headers: authHeaders(),
    });
    if (!response.ok) {
      const message = await readErrorBody(response);
      throw new Error(message || 'Não foi possível carregar as transações.');
    }
    const data = await response.json();
    if (!Array.isArray(data)) {
      throw new Error('Resposta inesperada do backend ao carregar transações.');
    }
    return data as BackendTransacao[];
  },

  /**
   * Create a transaction in the backend and return the cd_id it generated.
   * Calls: POST /api/v1/transacao/criar
   */
  async criar(input: NovaTransacaoInput): Promise<number> {
    const payload: CriarTransacaoPayload = {
      valor: input.valor,
      descricao: input.descricao,
      data: toBackendDate(input.data),
      categoria_id: Number(input.categoriaId),
      user_id: getUserIdFromToken(getToken()),
      observacao: input.observacao?.trim() || null,
    };

    if (!Number.isFinite(payload.valor) || payload.valor <= 0) {
      throw new Error('Informe um valor maior que zero.');
    }
    if (!payload.descricao.trim()) {
      throw new Error('Informe uma descrição.');
    }
    if (!Number.isInteger(payload.categoria_id)) {
      throw new Error('Escolha uma categoria válida.');
    }

    let response: Response;
    try {
      response = await fetch(`${API_URL}/api/v1/transacao/criar`, {
        method: 'POST',
        headers: authHeaders(),
        body: JSON.stringify(payload),
      });
    } catch {
      throw new Error(`Não foi possível alcançar o backend em ${API_URL}. Ele está rodando?`);
    }

    if (!response.ok) {
      const backendMessage = await readErrorBody(response);
      throw new Error(backendMessage || defaultErrorForStatus(response.status));
    }

    const data = await response.json().catch(() => null) as { id?: number } | null;
    if (!data || !Number.isInteger(data.id)) {
      throw new Error('O backend não devolvou o id da transação criada.');
    }
    return data.id;
  },

  /**
   * Edita uma transação existente pelo cd_id.
   * Calls: PUT /api/v1/transacao/atualizar?id={transacaoId}
   */
  async atualizar(transacaoId: number, input: NovaTransacaoInput): Promise<void> {
    if (!Number.isInteger(transacaoId)) {
      throw new Error('ID de transação inválido.');
    }
    const payload = {
      id: transacaoId,
      valor: input.valor,
      descricao: input.descricao,
      data: toBackendDate(input.data),
      categoria_id: Number(input.categoriaId),
      user_id: getUserIdFromToken(getToken()),
      observacao: input.observacao?.trim() || null,
    };

    let response: Response;
    try {
      response = await fetch(
        `${API_URL}/api/v1/transacao/atualizar`,
        { method: 'POST', headers: authHeaders(), body: JSON.stringify(payload) },
      );
    } catch {
      throw new Error(`Não foi possível alcançar o backend em ${API_URL}. Ele está rodando?`);
    }

    if (!response.ok) {
      const backendMessage = await readErrorBody(response);
      throw new Error(backendMessage || defaultErrorForStatus(response.status, 'atualizar'));
    }
  },

  /**
   * Exclui a transação pelo cd_id.
   * Calls: DELETE /api/v1/transacao/deletar?id={transacaoId}
   */
  async deletar(transacaoId: number): Promise<void> {
    if (!Number.isInteger(transacaoId)) {
      throw new Error('ID de transação inválido.');
    }

    let response: Response;
    try {
      response = await fetch(
        `${API_URL}/api/v1/transacao/deletar?id=${encodeURIComponent(String(transacaoId))}`,
        { method: 'DELETE', headers: authHeaders() },
      );
    } catch {
      throw new Error(`Não foi possível alcançar o backend em ${API_URL}. Ele está rodando?`);
    }

    if (!response.ok) {
      const backendMessage = await readErrorBody(response);
      throw new Error(backendMessage || defaultErrorForStatus(response.status, 'excluir'));
    }
  },
};
